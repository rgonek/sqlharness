import assert from "node:assert/strict"
import { dirname, join } from "node:path"
import { fileURLToPath, pathToFileURL } from "node:url"
const here = dirname(fileURLToPath(import.meta.url))
const playwrightPath = process.env.PLAYWRIGHT_CORE_PATH ?? "D:/Dev/CivicLens/frontend/node_modules/playwright-core/index.mjs"
const { chromium } = await import(pathToFileURL(playwrightPath))
const executablePath = process.env.CHROMIUM_PATH ?? "C:/Users/rgone/AppData/Local/ms-playwright/chromium-1228/chrome-win64/chrome.exe"
const browser = await chromium.launch({ headless: true, executablePath })
const errors = []
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 }, reducedMotion: "reduce" })
  page.on("pageerror", error => errors.push(error.message))
  page.on("console", message => { if (message.type() === "error") errors.push(message.text()) })
  page.on("response", response => { if (response.status() >= 400) errors.push(`HTTP ${response.status()} ${response.url()}`) })
  await page.route("**/favicon.ico", route => route.fulfill({ status: 204, body: "" }))
  await page.goto("http://127.0.0.1:4173/task-10-browser-fixture.html", { waitUntil: "domcontentloaded" })
  await page.evaluate(theme => document.documentElement.classList.toggle('dark', theme === 'dark'), process.env.THEME ?? 'light')
  const wide = page.locator('table[aria-label="Wide fixture"]')
  await wide.waitFor({ timeout: 60000 })
  assert.equal(await wide.locator("thead th").count(), 8)
  assert.equal(await wide.locator('th[scope="row"]').filter({ hasText: "row heading" }).count(), 1)
  const matrix = page.locator('[role="region"][aria-label="Dense row by Dense column matrix"]')
  const sticky = matrix.locator('tbody th[scope="row"]').first()
  const stickyBefore = await sticky.evaluate(el => ({ left: getComputedStyle(el).left, position: getComputedStyle(el).position, x: el.getBoundingClientRect().x }))
  await matrix.evaluate(el => { el.scrollLeft = 600 })
  const stickyAfter = await sticky.evaluate(el => ({ x: el.getBoundingClientRect().x, scrollLeft: el.closest('[role="region"]').scrollLeft }))
  assert.equal(stickyBefore.position, "sticky")
  assert.equal(stickyBefore.left, "0px")
  assert.ok(stickyAfter.scrollLeft > 0)
  assert.ok(Math.abs(stickyBefore.x - stickyAfter.x) < 1, JSON.stringify({ stickyBefore, stickyAfter }))
  assert.ok(await matrix.evaluate(el => el.scrollWidth > el.clientWidth))
  const dialog = page.getByRole("dialog")
  await dialog.waitFor({ timeout: 60000 })
  const viewport = await page.evaluate(() => ({ width: innerWidth, height: innerHeight }))
  const dialogBox = await dialog.boundingBox()
  assert.ok(dialogBox && dialogBox.x >= 0 && dialogBox.x + dialogBox.width <= viewport.width, JSON.stringify({ viewport, dialogBox }))
  const params = dialog.getByRole("table")
  const longValue = "parameter_value_".repeat(140)
  const valueCell = params.getByText(longValue)
  assert.equal(await valueCell.count(), 1)
  const cellBox = await valueCell.boundingBox()
  assert.ok(cellBox && cellBox.width < 700 && cellBox.x + cellBox.width <= dialogBox.x + dialogBox.width, JSON.stringify({ dialogBox, cellBox }))
  await valueCell.evaluate(el => { const range = document.createRange(); range.selectNodeContents(el); getSelection()?.removeAllRanges(); getSelection()?.addRange(range) })
  assert.ok(await page.evaluate(() => Boolean(getSelection()?.toString().startsWith("parameter_value_"))))
  await page.setViewportSize({ width: 320, height: 800 })
  await page.waitForFunction(() => { const popup = document.querySelector('[role="dialog"]'); return popup && popup.getBoundingClientRect().height <= innerHeight })
  const narrowDialog = await dialog.boundingBox()
  assert.ok(narrowDialog && narrowDialog.x >= 0 && narrowDialog.x + narrowDialog.width <= 320, JSON.stringify(narrowDialog))
  const parameterScroller = params.locator("xpath=ancestor::*[@data-slot='table-container']")
  const scroll = await parameterScroller.evaluate(el => ({ client: el.clientWidth, width: el.scrollWidth, overflowX: getComputedStyle(el).overflowX }))
  assert.ok(scroll.width >= scroll.client, JSON.stringify(scroll))
  assert.deepEqual(errors, [])
  await page.screenshot({ path: join(here, "task11-10-theme.png"), fullPage: true })
  process.stdout.write(JSON.stringify({ columnHeaders: 8, rowHeader: true, matrixSticky: { before: stickyBefore, after: stickyAfter }, matrixContainedScroll: true, approvalDialogContained: dialogBox, longParameterWrappedAndSelectable: { cellBox, selected: true }, narrowApproval: { dialog: narrowDialog, tableContainer: scroll }, consoleErrors: errors }, null, 2) + "\n")
} finally { await browser.close() }
