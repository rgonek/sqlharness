import fs from 'node:fs/promises';
import {setup,launch} from './layout-polish-fixtures.mjs';
import {usageData} from './screenshot-usage-fixture.mjs';
const root=process.env.SQLHARNESS_VISUAL_ROOT,out=root+'/plans/121-evidence/layout-polish/screenshot-details';
const b=await launch(),p=await b.newPage({viewport:{width:1280,height:900}}),checks=[],errors=[];await setup(p);
p.on('pageerror',e=>errors.push(e.message));p.on('console',m=>{if(m.type()==='error')errors.push(m.text())});
await p.route('**/api/stats?*',r=>r.fulfill({json:usageData()}));
const check=(value,name)=>{checks.push({name,passed:!!value});if(!value)throw Error(name)};
await p.goto('http://127.0.0.1:48138/stats');const summary=p.locator('[aria-label="Usage summary"]');await summary.waitFor();
const failure=await summary.getByText('Failed / rejected',{exact:true}).locator('..').innerText();
check(/0\s*\/\s*1/.test(failure),'Failed/rejected main count retained');
check(/16[.,]7%/.test(failure),'Failure percentage derives from six-operation cohort');
check((await summary.innerText()).includes('2 sessions'),'Actual fixture session count displayed');
check((await summary.innerText()).includes('1,000'),'Measured output token estimate displayed');
check(await p.getByText('Detailed usage and workflow accounting',{exact:true}).count()===0,'Detailed accounting disclosure removed');
check(await p.getByText('Operations per day (UTC)',{exact:true}).count()===0,'Removed disclosure contents not exposed elsewhere');
const sql=p.getByRole('region',{name:'Top SQL',exact:true});
check(await sql.getByRole('columnheader',{name:'Logical reads',exact:true}).count()===1,'Top SQL logical reads column present');
const reads=p.getByRole('radio',{name:'Logical reads',exact:true});await reads.click();
check(await reads.isChecked(),'Logical reads order selected');
check((await sql.locator('tbody tr').first().innerText()).includes('cccc'),'Reads-ranked leader displayed first');
check((await sql.locator('tbody tr').first().innerText()).includes('100,000'),'Recorded logical-read sum rendered');
await p.screenshot({path:out+'/usage-logical-reads-app.png',fullPage:true});
await p.setViewportSize({width:390,height:900});
check(await p.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Usage mobile has no document overflow');
await p.screenshot({path:out+'/usage-logical-reads-mobile.png',fullPage:true});
check(errors.length===0,'No Usage check app page/console errors');
await fs.writeFile(out+'/usage-check-results.json',JSON.stringify({checks,errors,fixtureOnly:true},null,2));await b.close();console.log('PASS '+checks.length+' Usage checks');
