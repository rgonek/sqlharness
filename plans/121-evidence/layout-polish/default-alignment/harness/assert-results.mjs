import fs from 'node:fs/promises';
const root=process.env.SQLHARNESS_VISUAL_ROOT,out=root+'/plans/121-evidence/layout-polish/default-alignment';
const read=async name=>JSON.parse(await fs.readFile(out+'/'+name,'utf8'));
const main=await read('browser-results.json'),details=await read('detail-results.json'),fields=await read('field-results.json');
const checks=[];
const check=(value,name)=>{checks.push({name,passed:!!value});if(!value)throw Error(name)};
check(main.errors.filter(e=>new URL(e.url).port==='48138').length===0,'No application page or console errors in main captures');
for(const c of main.checks)check(c.passed,c.name);
for(const p of main.pages.filter(p=>p.name.endsWith('-app')))check(p.overflow.scroll<=p.overflow.width,'No document overflow: '+p.name);
check(fields.labelClick.changed,'Settings visible label toggles switch');
check(!!fields.switchInfo.ariaDescribedBy,'Switch has description');
check(fields.switchDescriptions.every(s=>!!s.description),'All captured switches have descriptions');
check(fields.invalid.invalid==='true','Invalid number exposes invalid state');
check(fields.invalid.describedBy.split(' ').includes(fields.errorInfo.id),'Input references visible error');
check(fields.invalid.errorMessage===fields.errorInfo.id,'Input error-message relation matches');
check(fields.errorInfo.role==='alert','Error is announced');
const detail=name=>details.checks.find(c=>c.name===name)?.value;
check(detail('Version A ArrowDown selected values')==='A v1','Native ArrowDown selects next A version');
check(detail('Version table radio count')===6,'A/B renders native radio choices');
for(const name of ['Settings switch Space toggles','Review Enter opens dialog','Approve initially disabled','Approve enabled after delay','Escape closes dialog'])check(detail(name)===true,name);
check(!!detail('Dialog has accessible name'),'Mutation dialog accessible name');
check(!details.requests.some(r=>r.url.includes('/api/mutations/')&&r.method!=='GET'),'No mutation decisions submitted');
const mobile=detail('Mutation mobile overflow');check(mobile.scroll<=mobile.viewport,'No mutation document overflow');
await fs.writeFile(out+'/browser-check-summary.json',JSON.stringify({checks,passed:checks.length},null,2));
console.log('PASS '+checks.length+' browser checks');
