import { setup, launch, sessions, ops } from './app-capture.mjs';
import fs from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import os from 'node:os';
import path from 'node:path';
const installed=process.env.SQLHARNESS_CHECK_INSTALLED==='1';
const endpoint=installed?JSON.parse(await fs.readFile(path.join(process.env.SQLHARNESS_HOME||path.join(os.homedir(),'.sqlharness'),'dashboard.json'),'utf8')):null;
const origin=endpoint?`http://127.0.0.1:${endpoint.port}`:'http://127.0.0.1:48126';
const out=new URL('../../shadcn/ui-information/'+(installed?'installed/':''),import.meta.url);await fs.mkdir(out,{recursive:true});
const browser=await launch(),results=[],errors=[];
const assert=(ok,message)=>{if(!ok)throw Error(message)};
try {
 const page=await browser.newPage({viewport:{width:1280,height:1000}});await setup(page);
 if(endpoint)await page.context().addCookies([{name:'sqlharness_dashboard',value:endpoint.token,url:origin,httpOnly:true,sameSite:'Strict'}]);
 page.on('pageerror',e=>errors.push(e.message));
 await page.route('**/api/sessions/1',route=>route.fulfill({json:{session:sessions[0],operations:ops,note:null,conversations:[{agentKind:'codex',conversationId:'conversation-fixture-1',title:'Orders investigation',operations:8}],compareSubjects:[],unassignedCompareCount:0}}));
 await page.goto(origin+'/sessions/1');
 await page.getByRole('button',{name:'Add note',exact:true}).waitFor();
 assert(!await page.getByRole('region',{name:'Conversations'}).isVisible(),'Conversations initially visible');
 await page.getByRole('button',{name:'Session metadata'}).click();
 await page.getByText('Orders investigation',{exact:true}).waitFor();
 const note=await page.getByRole('button',{name:'Add note',exact:true}).boundingBox();
 const optimization=await page.getByText('Optimization',{exact:true}).first().boundingBox();
 assert(note.y<optimization.y,'Add note is below Optimization');
 assert(await page.getByRole('button',{name:'Select comparison',exact:true}).count()===0,'Redundant comparison CTA remains');
 await page.screenshot({path:fileURLToPath(new URL('session-details.png',out)),fullPage:true});
 const resize=async(label,frame)=>{
  await frame.scrollIntoViewIfNeeded();const before=await frame.boundingBox();
  await page.mouse.move(before.x+before.width-3,before.y+before.height-3);await page.mouse.down();
  await page.mouse.move(before.x+before.width-3,before.y+before.height+137,{steps:15});await page.mouse.up();
  await page.waitForTimeout(400);const after=await frame.boundingBox();
  assert(after.height>before.height+80,label+' did not resize');
  const editor=await frame.locator('.monaco-editor:visible').first().boundingBox();
  assert(Math.abs(editor.height-after.height)<8,label+' Monaco did not follow frame');
  results.push({label,before:before.height,after:after.height,editor:editor.height});
 };
 await page.locator('[data-slot=sql-editor-frame] .monaco-editor:visible').first().waitFor();
 await resize('side-by-side diff',page.locator('[data-slot=sql-editor-frame]').first());
 await page.getByRole('radio',{name:'Unified',exact:true}).click();
 await resize('unified diff',page.locator('[data-slot=sql-editor-frame]').first());
 await page.getByRole('tab',{name:'Plan',exact:true}).click();
 await page.getByRole('region',{name:'Executed SQL',exact:true}).locator('.monaco-editor:visible').waitFor();
 await resize('plan SQL',page.getByRole('region',{name:'Executed SQL',exact:true}).locator('[data-slot=sql-editor-frame]'));
 await page.screenshot({path:fileURLToPath(new URL('resized-plan.png',out)),fullPage:true});
 await page.setViewportSize({width:390,height:1000});await page.waitForTimeout(500);
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Narrow plan overflows');
 await page.screenshot({path:fileURLToPath(new URL('narrow-plan.png',out)),fullPage:true});
 await page.setViewportSize({width:1280,height:1000});await page.goto(origin+'/operations/23');
 await page.getByRole('tab',{name:'Details',exact:true}).click();
 await page.getByRole('button',{name:'SQL diff & conditions',exact:true}).click();
 await page.getByRole('tab',{name:'Baseline',exact:true}).click();
 await page.locator('[data-slot=sql-editor-frame] .monaco-editor:visible').first().waitFor();
 await resize('single-side SQL',page.locator('[data-slot=sql-editor-frame]').first());
 assert(errors.length===0,errors.join('\n'));
 await fs.writeFile(new URL('results.json',out),JSON.stringify({origin,installed,pid:endpoint?.pid,results,errors,api:'browser fixtures only',tokenRecorded:false},null,2));console.log('PASS',results);
}finally{await browser.close()}
